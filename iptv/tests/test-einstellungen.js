const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })).newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:8080');
  const f = p.locator('#loginForm');
  await f.locator('[name=server]').fill('localhost:9000'); await f.locator('[name=username]').fill('max'); await f.locator('[name=password]').fill('geheim');
  await f.locator('button').click(); await p.waitForSelector('.tiles .tile');
  console.log('Kopfleiste Knoepfe sichtbar:', await p.locator('.topbar .pill-btn:visible').count());
  await p.click('.rail [data-tab=settings]'); await p.waitForSelector('.stile');
  console.log('Kacheln:', await p.locator('.stile .s-title').allTextContents());
  await p.screenshot({ path: __dirname + '/v12-einstellungen.png' });
  await p.click('.rail [data-tab=vod]'); await p.waitForSelector('.main .card'); await p.click('.cat[data-cat="__all"]');
  const all = await p.locator('.main .card').evaluateAll((cs) => cs.map((c) => c.querySelector('.title').textContent + ((c.querySelector('.b4k') || {}).textContent ? ' [' + c.querySelector('.b4k').textContent + ']' : '')));
  console.log('Alle Qualitaeten:', all.length, all.filter((t) => /DVD|720|Bluray|Drama/.test(t)));
  await p.click('.rail [data-tab=settings]'); await p.click('.stile.c1'); await p.waitForSelector('.q-opts');
  await p.locator('.q-opt', { hasText: 'Ab 1080p' }).locator('input').check();
  console.log(await p.textContent('#qualBody > .muted:last-child'));
  await p.screenshot({ path: __dirname + '/v12-qualitaet.png' });
  await p.keyboard.press('Escape');
  await p.click('.rail [data-tab=vod]'); await p.waitForSelector('.main .card'); await p.click('.cat[data-cat="__all"]');
  const q = await p.locator('.main .card .title').allTextContents();
  console.log('Ab 1080p:', q.length, '| DVDRip/720p weg:', !q.some((t) => /DVDRip|720p|Alter Film|Mittlerer/.test(t)), '| Bluray da:', q.some((t) => /Bluray/.test(t)));
  await p.click('.rail [data-tab=settings]'); await p.click('.stile.c1');
  await p.locator('#qualBody input[type=checkbox]').uncheck();
  await p.keyboard.press('Escape');
  await p.click('.rail [data-tab=vod]'); await p.waitForSelector('.main .card'); await p.click('.cat[data-cat="__all"]');
  console.log('Ohne Unbekannte:', await p.locator('.main .card .title').allTextContents());
  await p.click('.rail [data-tab=settings]'); await p.click('.stile.c7'); await p.waitForSelector('#qualBody h2');
  console.log('Konto:', (await p.locator('#qualBody .f-row').allTextContents()).slice(0, 3));
  await p.keyboard.press('Escape');
  await p.click('.stile.c8'); await p.waitForSelector('#qualBody h2');
  console.log('Info:', (await p.locator('#qualBody .f-row').allTextContents()).slice(0, 3));
  console.log('Seitenfehler:', errs);
  await b.close();
})().catch((e) => { console.error('FEHLER', e.message); process.exit(1); });
