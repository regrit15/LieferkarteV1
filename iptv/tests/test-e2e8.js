const { chromium } = require('playwright');
const log = (...a) => console.log(...a);
const groups = (p) => p.locator('#sidebar .side-group').allTextContents();
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 1440, height: 880 }, deviceScaleFactor: 2 })).newPage();
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:8080');
  const f = p.locator('#loginForm');
  await f.locator('[name=server]').fill('localhost:9000');
  await f.locator('[name=username]').fill('max');
  await f.locator('[name=password]').fill('geheim');
  await f.locator('button').click();
  await p.waitForSelector('.tiles .tile'); await p.click('.rail [data-tab=live]'); await p.waitForSelector('.main .row');
  log('Live Gruppen:', await groups(p));
  log('Start-Kategorie:', await p.textContent('.cat.active'));
  log('Fussball & F1 Sender:', (await p.locator('.row .name').allTextContents()).filter((n) => !/^Sender \d/.test(n)));
  await p.click('.cat[data-cat="__f1"]');
  log('Nur Formel 1:', await p.locator('.row .name').allTextContents());
  await p.waitForFunction(async () => (await localApi('GET', '/epg/status?account=' + encodeURIComponent(accountKey()))).status === 'bereit', null, { polling: 1000, timeout: 60000 });
  await p.waitForFunction(() => Number(document.querySelector('.cat[data-cat="__livefocus"] .n').textContent) > 0, null, { timeout: 20000 });
  await p.click('.cat[data-cat="__livefocus"]');
  await p.waitForSelector('.row');
  log('Jetzt live:', await p.locator('.row .name').allTextContents());
  await p.screenshot({ path: __dirname + '/v8-live.png' });

  await p.click('[data-tab=vod]');
  await p.waitForSelector('.card');
  log('Filme Gruppen:', await groups(p), '| Start:', await p.textContent('.cat.active'));
  log('Aktuell:', await p.locator('.card .title').allTextContents());
  await p.click('.cat[data-cat="__added"]');
  log('Neu hinzugefuegt:', await p.locator('.card .title').allTextContents(), '| Sortierauswahl sichtbar:', await p.locator('#sortSel').isVisible());
  await p.click('.cat[data-cat="__top"]');
  log('Top bewertet:', await p.locator('.card .title').allTextContents());
  await p.click('.cat[data-cat="__all"]');
  log('Alle (Neueste zuerst):', (await p.locator('.card .title').allTextContents()).slice(0, 4));
  await p.selectOption('#sortSel', 'name');
  log('Alle (A-Z):', (await p.locator('.card .title').allTextContents()).slice(0, 4));
  log('IMDb-Hinweis sichtbar:', await p.locator('.imdb-hint').count(), '| Knopf:', await p.textContent('#imdbBtn'));

  await p.click('.imdb-hint .btn.primary');
  await p.fill('#imdbBody input', 'falsch');
  await p.click('#imdbBody .btn.primary');
  await p.waitForFunction(() => document.querySelector('#imdbBody .error').textContent.length > 0);
  log('Falscher Schluessel:', await p.textContent('#imdbBody .error'));
  await p.fill('#imdbBody input', 'testkey');
  await p.click('#imdbBody .btn.primary');
  await p.waitForSelector('.card .imdb', { timeout: 15000 });
  await p.waitForTimeout(800);
  const cards = await p.locator('.card').evaluateAll((cs) => cs.map((c) => c.querySelector('.title').textContent + ' -> ' + ((c.querySelector('.imdb') || {}).textContent || '-')));
  log('IMDb auf Postern:', cards);
  log('Knopf:', await p.textContent('#imdbBtn'));
  await p.screenshot({ path: __dirname + '/v8-filme.png' });
  await p.locator('.card', { hasText: 'Wunder' }).click();
  await p.waitForSelector('.imdb-line .imdb');
  log('Detail IMDb:', await p.textContent('.imdb-line'), '| Link:', await p.getAttribute('.imdb-line a', 'href'));
  await p.keyboard.press('Escape');

  await p.click('[data-tab=series]');
  await p.waitForSelector('.card');
  log('Serien Gruppen:', await groups(p));
  await p.click('.cat[data-cat="__all"]');
  await p.waitForSelector('.card .imdb', { timeout: 15000 });
  log('Serien IMDb:', await p.locator('.card').evaluateAll((cs) => cs.map((c) => c.querySelector('.title').textContent + ' -> ' + ((c.querySelector('.imdb') || {}).textContent || '-'))));
  log('Seitenfehler:', errs);
  await b.close();
})().catch((e) => { console.error('FEHLER', e.message); process.exit(1); });
